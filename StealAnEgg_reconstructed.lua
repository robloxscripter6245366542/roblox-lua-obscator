Webhook = {}
function Webhook.httpPost(url: string, body: string)     -- decoded "httpPost"
    local req = (syn and syn.request) or (http and http.request) or request
    if req then
        req({ Url = url, Method = "POST",
              Headers = { ["Content-Type"] = "application/json" }, Body = body })
    end
end

function Webhook.formatElapsed(secs: number): string
    local h = math.floor(secs / 3600); local m = math.floor((secs % 3600) / 60)
    if h > 0 then return string.format("%dh %dm", h, m) end
    return string.format("%dm %ds", m, math.floor(secs % 60))
end

-- decoded FN695: builds the "Session Summary" embed
function Webhook.buildSummaryEmbed()
    return {
        title = "Session Summary",
        description = string.format(
            "**Player** `%s`\n**Server** `%s`\n**Runtime** `%s`",
            string.format("%s [%s]", LocalPlayer.Name, LocalPlayer.UserId),
            game.JobId,
            Webhook.formatElapsed(os.clock() - Stats.startClock)),
        fields = {
            { name = "Eggs stolen",   value = string.format("**%d**", Stats.eggsStolen),   inline = true },
            { name = "Pets obtained", value = string.format("**%d**", Stats.petsObtained), inline = true },
            { name = "Rebirths",      value = string.format("**%d**", Stats.rebirths),     inline = true },
        },
    }
end

function Webhook.webhookPing(): string?                   -- decoded "webhookPing"
    if Config.WebhookPingId ~= "" then return "<@" .. Config.WebhookPingId .. ">" end
    return nil
end

-- decoded FN200: sends any embed to the configured webhook
function Webhook.sendWebhookEmbed(embed)
    if not isOn("WebhookEnabled") or Config.WebhookUrl == "" then return end
    Webhook.httpPost(Config.WebhookUrl, HttpService:JSONEncode({
        username = "Ouroboros Hub",
        content  = Webhook.webhookPing(),
        embeds   = { embed },
    }))
end

function Webhook.sendSummary() Webhook.sendWebhookEmbed(Webhook.buildSummaryEmbed()) end
function Webhook.runWebhookSummary()
    while true do
        task.wait((Config.WebhookInterval or 5) * 60)
        Webhook.sendSummary()
    end
end
