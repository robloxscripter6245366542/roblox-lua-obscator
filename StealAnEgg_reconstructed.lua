Hop = {}
Hop.visited = {} :: { [string]: boolean }
local SERVERS_URL =
    "https://games.roblox.com/v1/games/%d/servers/Public?sortOrder=Asc&excludeFullGames=true&limit=100"

function Hop.fetchServerPage(cursor: string?)
    local url = string.format(SERVERS_URL, game.PlaceId)
    if cursor then url ..= "&cursor=" .. cursor end
    local ok, body = pcall(function() return (game :: any):HttpGet(url) end)
    if not ok then return nil end
    return HttpService:JSONDecode(body)
end

-- decoded FN1106: page through public servers, skip full/visited/current
function Hop.pickHopTargets(): string?
    local cursor = nil
    repeat
        local page = Hop.fetchServerPage(cursor)
        if not page or type(page.data) ~= "table" then return nil end
        for _, srv in ipairs(page.data) do
            if srv.playing < srv.maxPlayers
               and srv.id ~= game.JobId
               and not Hop.visited[srv.id] then
                return srv.id
            end
        end
        cursor = page.nextPageCursor
    until not cursor
    return nil
end

function Hop.rememberVisited(jobId: string) Hop.visited[jobId] = true end   -- decoded "rememberVisited"

-- decoded FN763 serverHop(reason): won't hop while carrying; flushes webhook first
function Hop.serverHop(reason: string)
    if Steal.isCarrying and Steal.isCarrying() then return end   -- decoded "isCarrying" guard
    local jobId = Hop.pickHopTargets()
    if not jobId then
        warn("Server hop failed, retrying in 10s")
        task.wait(10)
        return Hop.serverHop(reason)
    end
    Hop.rememberVisited(jobId)
    if Config.WebhookEnabled then Webhook.sendSummary() end       -- decoded "sendSummary" before leaving
    Hop.queueRelaunch()
    TeleportService:TeleportToPlaceInstance(game.PlaceId, jobId, LocalPlayer)
end

-- re-inject this same script into the next server (decoded queue_on_teleport path)
function Hop.queueRelaunch()
    local q = (syn and syn.queue_on_teleport) or queue_on_teleport
    if q then
        q('loadstring(game:HttpGet("'
          .. "https://raw.githubusercontent.com/joustingmatch/Ouroboros/main/games/stealanegg.lua"
          .. '"))()')
    end
end

-- Auto Reconnect (decoded handleDisconnect / rejoinServer)
