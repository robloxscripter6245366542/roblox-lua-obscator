local function formatNumber(n: number): string
    local suf, i = { "", "K", "M", "B", "T" }, 1
    while n >= 1000 and i < #suf do n /= 1000; i += 1 end
    return string.format("%.2f%s", n, suf[i])
end

-- =============================================================================
--  NETWORKING  (decoded netCall / netInvoke / netRemote wrappers)
-- =============================================================================
local Net = {}
local _remoteCache: { [string]: Instance } = {}

function Net.remote(name: string): Instance?
    if _remoteCache[name] and _remoteCache[name].Parent then return _remoteCache[name] end
    local r = ReplicatedStorage:FindFirstChild(name, true)   -- VERIFY: real remotes may live under a Net/Remotes folder
    if r then _remoteCache[name] = r end
    return r
end
function Net.call(name: string, ...)                 -- RemoteEvent:FireServer
    local r = Net.remote(name)
    if r and r:IsA("RemoteEvent") then r:FireServer(...) end
end
function Net.invoke(name: string, ...): any          -- RemoteFunction:InvokeServer
    local r = Net.remote(name)
    if r and r:IsA("RemoteFunction") then return r:InvokeServer(...) end
    return nil
end

-- =============================================================================
--  EGG DATA MODEL  (decoded getAreaEggs / getSave)
