-- decoded "selectionAllows": a multi-select passes if empty (allow all) or contains v
local function selectionAllows(key: string, v: any): boolean
    local sel = Config[key]
    if type(sel) ~= "table" then return true end
    if next(sel) == nil then return true end
    return sel[v] == true or table.find(sel, v) ~= nil
end

