local Steal = {}

-- decoded FN1755 isStealCandidate(egg, allowAll)
function Steal.isStealCandidate(egg, allowAll: boolean?): boolean
    if typeof(egg.Uid) ~= "string" then return false end
    if egg.State == "Slot" then return false end          -- already slotted on a plot
    if egg.State == "Dead" then return false end
    if not allowAll and egg.State == "Dropped" then return false end  -- VERIFY: dropped gate
    if not selectionAllows("StealZones", egg.AreaId) then return false end
    if Config.StealBigEggs and not Eggs.isBigEgg(egg) then return false end
    return Eggs.matchesEggFilters(egg, "StealZones", "StealRarities", "StealMutations")
end

-- decoded FN47 pickStealTarget: scans area eggs, scores by StealPriority, nearest root
function Steal.pickStealTarget()
    local eggs = Eggs.getAreaEggs()
    local root = getRoot()
    local priority = optionValue("StealPriority", "Rarest")
    local best, bestScore = nil, -math.huge
    for _, egg in ipairs(eggs) do
        if Steal.isStealCandidate(egg, Config.AutoStealAll) then
            local score
            if priority == "Nearest" and root then
                score = -(root.Position - egg.Position).Magnitude
            elseif priority == "Furthest" and root then
                score =  (root.Position - egg.Position).Magnitude
            elseif priority == "Biggest Size" then
                score = egg.Scale or 0
            else -- "Rarest" (default) and rarity-ranked modes
                score = Steal.eggScore(egg)               -- decoded "eggScore"
            end
            if score > bestScore then best, bestScore = egg, score end
        end
    end
    return best
end

function Steal.eggScore(egg): number                      -- decoded "eggScore"
    -- higher = rarer; real impl ranks by resolved rarity index (+ size tiebreak)
    return (egg.RarityRank or 0) + (egg.Scale or 0) * 1e-3   -- VERIFY: rarity ordering
end

-- decoded FN402 stealEgg(target): path to the egg, carry it, return toward base
function Steal.stealEgg(target)
    if not Steal.stealingEnabled() then return end        -- decoded "stealingEnabled"
    local root = getRoot()
    if not root then return end
    local pos = Steal.getSlotEggPosition(target) or target.Position  -- decoded "getSlotEggPosition"
    Steal.tweenTo(pos)                                     -- decoded "tweenTo" (or tryTeleportTo)
    task.wait(Config.GrabDelay)
    Steal.tryCarryEgg(target)                              -- decoded "tryCarryEgg"
    if Config.AutoReturn then
        Steal.tweenTo(Steal.getBasePosition(), Config.ReturnPace)  -- return via CorridorMidpoint
    end
end

function Steal.tryCarryEgg(target): boolean               -- decoded "tryCarryEgg"
    if Steal.eggInventoryFull() then
        Steal.stealBlockedByInventory = true              -- decoded flag
        return false
    end
    Net.call("RequestCarryAreaEgg", target.Uid)           -- VERIFY: arg = Uid (string)
    Stats.eggsStolen += 1
    return true
end

function Steal.eggInventoryFull(): boolean
    return Steal.eggInventoryCount() >= Config.MAX_INVENTORY   -- decoded "eggInventoryCount/Full"
end

-- decoded FN564 runAutoSteal: the main loop
function Steal.runAutoSteal()
    while true do
        if isOn("AutoStealEgg") then
            local target = Steal.pickStealTarget()
            if target and not Steal.eggInventoryFull() then
                Steal.stealEgg(target)
            elseif Config.AutoServerHop and Config.HopMode == "No Matching Eggs" then
                Hop.serverHop("No matching eggs in this server")   -- decoded "requested"
            end
        end
        task.wait(Config.GrabDelay)
    end
end

-- placement / drop / hatch companion loops (decoded runAutoPlaceEggs / runAutoDropEgg / runAutoOpenReadyEggs)
function Steal.runAutoPlaceEggs()
    while true do
        if isOn("AutoPlaceAll") or isOn("AutoPlaceSelected") then
            for _, uid in ipairs(Eggs.getUnplacedEggUids()) do
                Net.call("RequestPlaceEgg", uid)          -- VERIFY: may take (uid, cframe)
                task.wait(0.15)
            end
        end
        task.wait(1)
    end
end
function Steal.runAutoDropEgg()
    while true do
        if isOn("AutoDropEgg") then Net.call("RequestDropHeldAreaEgg") end
        task.wait(1)
    end
end
function Steal.runAutoOpenReadyEggs()
    while true do
        if isOn("AutoOpenReadyEggs") then
            Net.call("RequestHatchEgg")
            Net.call("RequestCompleteHatchEgg")
        end
        task.wait(1)
    end
end

