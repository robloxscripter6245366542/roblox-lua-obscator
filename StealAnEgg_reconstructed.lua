local Eggs = {}

-- decoded FN1659 getAreaEggs: snapshot via RemoteFunction, fall back to the event.
function Eggs.getAreaEggs()
    local snap = Net.invoke("GetAreaEggSnapshot")
    if not snap then
        Net.call("RequestAreaEggSnapshot")
        snap = Net.invoke("GetAreaEggSnapshot")
    end
    local out = {}
    if type(snap) == "table" and type(snap.Records) == "table" then
        for _, rec in ipairs(snap.Records) do
            if type(rec.Uid) == "string" then table.insert(out, rec) end
        end
    end
    return out
end

-- decoded FN1633 getUnplacedEggUids: read local save inventory, filter by lifecycle
function Eggs.getUnplacedEggUids()
    local save = Net.invoke("getSave") or {}          -- decoded "getSave"
    local inv  = save.EggInventory or {}
    local placement = save.Placement or {}
    local uids = {}
    for uid, egg in pairs(inv) do
        if type(uid) == "string" and not placement[uid] then
            if Eggs.matchesEggFilters(egg, "StealZones", "LifecycleRarities", "LifecycleMutations") then
                table.insert(uids, uid)
            end
        end
    end
    return uids
end

-- decoded FN859 matchesEggFilters(egg, zoneKey, rarityKey, mutationKey)
function Eggs.matchesEggFilters(egg, zoneKey: string, rarityKey: string, mutationKey: string): boolean
    local rarity = Eggs.resolveRarity(egg.AssetCategory)          -- decoded "resolveRarity"
    if type(rarity) ~= "string" then return false end            -- unknown rarity -> reject
    if not selectionAllows(rarityKey, rarity) then return false end
    if not Eggs.matchesMutationFilter(egg, mutationKey) then return false end  -- decoded "matchesMutationFilter"
    if zoneKey and egg.AreaId ~= nil and not selectionAllows(zoneKey, egg.AreaId) then
        return false
    end
    return true
end

function Eggs.resolveRarity(assetCategory: any): string?
    -- decoded: maps an egg's AssetCategory to a rarity bucket name
    -- (Common/Uncommon/Rare/Epic/Legendary/Mythic/Secret/Divine/Eternal/Cosmic/...)
    return assetCategory and tostring(assetCategory) or nil   -- VERIFY: real map is a lookup table
end
function Eggs.matchesMutationFilter(egg, mutationKey: string): boolean
    local want = Config[mutationKey]
    if type(want) ~= "table" or next(want) == nil then return true end
    for _, mut in ipairs(egg.Mutations or {}) do
        if selectionAllows(mutationKey, mut) then return true end
    end
    return false
end

function Eggs.isBigEgg(egg): boolean                 -- decoded "isBigEgg"
    return (egg.Scale or 0) >= Config.StealBigEggScale
end

-- =============================================================================
--  STEALING  (decoded isStealCandidate / pickStealTarget / stealEgg / runAutoSteal)
