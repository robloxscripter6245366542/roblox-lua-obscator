    TeleportService:Teleport(game.PlaceId, LocalPlayer)
end

-- =============================================================================
--  WEBHOOK TELEMETRY  (decoded FN200 sendWebhookEmbed, FN695 buildSummaryEmbed)
--  Opt-in. Streams player identity + server JobId + counters to Config.WebhookUrl.
